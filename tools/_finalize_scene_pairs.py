UNMATCHED_CLEAN = [51]  # ночная улица со знаком «неровная дорога» и клумбами из шин — нет stamped-кадра


def fname(n: int, ts: str) -> str:
    return f"photo_{n}_{ts}.jpg"


def main() -> None:
    pairs = []
    used_stamped = set()
    for i, (cn, sn, scene) in enumerate(PAIRS, start=1):
        lat, lon, acc, addr = GPS[sn]
        used_stamped.add(sn)
        pairs.append(
            {
                "id": i,
                "clean": fname(cn, CLEAN_TS),
                "stamped": fname(sn, STAMP_TS),
                "lat": lat,
                "lon": lon,
                "acc": acc,
                "addr": addr,
                "scene": scene,
            }
        )

    unused = [fname(n, STAMP_TS) for n in range(1, 52) if n not in used_stamped]
    unmatched = [fname(n, CLEAN_TS) for n in UNMATCHED_CLEAN]

    out = {
        "pairs": pairs,
        "unmatched_clean": unmatched,
        "unused_stamped": unused,
    }
    path = Path(r"c:\Users\root\d\tools\scene_pairs.json")
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"pairs={len(pairs)} unmatched={len(unmatched)} unused={len(unused)}")
    print("unused:", unused)
    print("unmatched:", unmatched)
    for p in pairs[:5]:
        print(p)


if __name__ == "__main__":
    main()
